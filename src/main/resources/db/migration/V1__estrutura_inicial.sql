-- Estrutura inicial do Margem.
-- Valores em dinheiro são NUMERIC(12,2): nunca ponto flutuante para dinheiro.
-- Datas são TIMESTAMP WITH TIME ZONE, gravadas em UTC e exibidas no fuso da loja.

CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login       VARCHAR(50)  NOT NULL UNIQUE,
    senha_hash  VARCHAR(100) NOT NULL,
    perfil      VARCHAR(20)  NOT NULL CHECK (perfil IN ('DONO', 'EXPEDICAO')),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE produto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(60)   NOT NULL UNIQUE,
    nome            VARCHAR(150)  NOT NULL,
    custo_unitario  NUMERIC(12,2) NOT NULL CHECK (custo_unitario >= 0),
    estoque_atual   INTEGER       NOT NULL,
    estoque_minimo  INTEGER       NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
    versao          BIGINT        NOT NULL DEFAULT 0,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE pedido (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(40)   NOT NULL UNIQUE,
    status             VARCHAR(30)   NOT NULL,
    origem             VARCHAR(20)   NOT NULL,
    criado_em          TIMESTAMP WITH TIME ZONE NOT NULL,
    prazo_envio        TIMESTAMP WITH TIME ZONE,
    desconto_vendedor  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (desconto_vendedor >= 0),
    taxa_comissao      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (taxa_comissao >= 0),
    taxa_servico       NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (taxa_servico >= 0),
    taxa_transacao     NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (taxa_transacao >= 0),
    taxas_estimadas    BOOLEAN       NOT NULL DEFAULT FALSE,
    versao             BIGINT        NOT NULL DEFAULT 0,
    importado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_pedido_criado_em ON pedido (criado_em);
CREATE INDEX idx_pedido_status_prazo ON pedido (status, prazo_envio);

CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    sku             VARCHAR(60)   NOT NULL,
    descricao       VARCHAR(255)  NOT NULL,
    quantidade      INTEGER       NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    -- Custo congelado no momento da venda. NULL = SKU ainda não cadastrado.
    custo_unitario  NUMERIC(12,2) CHECK (custo_unitario >= 0)
);

CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX idx_item_pedido_sku ON item_pedido (sku);

CREATE TABLE alerta_enviado (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(30) NOT NULL,
    referencia  VARCHAR(80) NOT NULL,
    enviado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_alerta_enviado_busca ON alerta_enviado (tipo, referencia, enviado_em);
